-- Langue active : réglage (fr/en) ou langue du jeu
function ns.SetLanguage(choice)
    local lang = choice
    if not lang or lang == "auto" then
        local loc = GetLocale and GetLocale() or "frFR"
        lang = loc:sub(1, 2) == "fr" and "fr" or "en"
    end
    ns.lang = lang
end
ns.SetLanguage("auto")

ns.L = setmetatable({}, { __index = function(_, k)
    if ns.lang == "en" then return EN[k] or k end
    return k
end })
